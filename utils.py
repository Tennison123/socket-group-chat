"""
utils.py  -  ฟังก์ชันช่วยเหลือเล็กๆ ที่ไม่ได้อยู่ฝั่งใดฝั่งหนึ่งโดยเฉพาะ
======================================================================
ตอนนี้มีฟังก์ชันเดียว คือหา "IP ของเครื่องเรา" เพื่อเอาไปให้เพื่อนใช้เข้ากลุ่ม
"""
import socket
def get_local_ip() -> str:
    """หา IP ของเครื่องนี้ในเครือข่าย (เช่น Wi-Fi หรือ LAN)
    ปัญหา: เครื่องหนึ่งเครื่องอาจมีหลาย IP (Wi-Fi, LAN, VPN, 127.0.0.1 ...)
    แล้วจะรู้ได้ยังไงว่าอันไหนคือ IP ที่เพื่อนจะใช้ติดต่อเรามาได้?

    วิธีที่ใช้: ลอง "แกล้งต่อ" ไปหาเซิร์ฟเวอร์ภายนอก (8.8.8.8 ของ Google)
    ระบบปฏิบัติการจะเลือกการ์ดเครือข่ายที่ใช้ออกอินเทอร์เน็ตจริงๆ ให้เอง
    แล้วเราก็แค่อ่านว่า IP ฝั่งเราที่ถูกเลือกคืออะไร
    (ใช้ UDP ซึ่งแค่ "เลือกเส้นทาง" ไม่ได้ส่งข้อมูลออกไปจริง จึงไม่ต้องมีเน็ตก็ลองได้)
    """
    s = socket.socket(socket.AF_INET, socket.SOCK_DGRAM)   # DGRAM = UDP
    try:
        s.connect(("8.8.8.8", 80))
        return s.getsockname()[0]      # IP ฝั่งเราที่ระบบเลือกใช้
    except OSError:
        # ไม่ได้ต่อเครือข่ายเลย -> ใช้ 127.0.0.1 (ตัวเอง) ไปก่อน
        # จะคุยกันได้แค่ในเครื่องเดียวกัน
        return "127.0.0.1"
    finally:
        s.close()                      # ปิด socket ทุกครั้ง ไม่ว่าจะสำเร็จหรือไม่