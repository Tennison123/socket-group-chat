"""
protocol.py  -  "ภาษากลาง" ที่ server กับ client ใช้คุยกัน
======================================================================
ปัญหา: คอมพิวเตอร์สองเครื่องส่งข้อมูลหากันผ่านเครือข่าย (TCP) ได้ก็จริง
แต่ TCP เป็นเหมือน "ท่อน้ำ" คือส่งตัวอักษรไหลไปเรื่อยๆ ไม่มีการบอกว่า
ข้อความหนึ่งๆ เริ่มและจบตรงไหน ดังนั้นเราต้องตกลงกันก่อนว่าจะส่งกันยังไง
ข้อตกลงของโปรแกรมนี้:
  1) ข้อความ 1 อัน = ข้อมูลแบบ JSON (dict ของ Python) 1 ก้อน
     เช่น {"type": "message", "text": "สวัสดี"}
  2) ปิดท้ายข้อความทุกอันด้วยการขึ้นบรรทัดใหม่ "\\n"
     ฝั่งรับจึงอ่านทีละบรรทัดก็จะได้ข้อความครบทีละอัน
ไฟล์นี้เก็บ "ชนิดของข้อความ" ทั้งหมด และฟังก์ชันแปลงข้อความไป-กลับ
ทั้ง server.py และ client.py จะ import ไฟล์นี้ไปใช้ร่วมกัน
"""
import json
# พอร์ตเริ่มต้นของโปรแกรม (พอร์ตเปรียบเหมือน "ช่องรับสัญญาณ" ของเครื่อง)
# ใช้เลข 1024-65535 ได้ เลขต่ำกว่านี้ระบบปฏิบัติการสงวนไว้ใช้งานอื่น
DEFAULT_PORT = 5555
# ชนิดของข้อความ (ฟิลด์ "type" ในทุกข้อความ) บอกว่าข้อความนี้ใช้ทำอะไร
JOIN = "join"          # client -> server : "ขอเข้ากลุ่ม" พร้อมชื่อผู้ใช้
WELCOME = "welcome"    # server -> client : "เข้ากลุ่มสำเร็จ" พร้อมชื่อห้องและรายชื่อสมาชิก
ERROR = "error"        # server -> client : "เข้าไม่ได้" พร้อมเหตุผล (เช่น ชื่อซ้ำ)
MESSAGE = "message"    # ทั้งสองทาง       : ข้อความแชทธรรมดา
SYSTEM = "system"      # server -> client : ประกาศจากระบบ เช่น "ใครสักคนเข้า/ออกกลุ่ม"
USERS = "users"        # server -> client : รายชื่อสมาชิกล่าสุดในกลุ่ม
LEAVE = "leave"        # client -> server : "ฉันขอออกจากกลุ่มแล้วนะ" (แจ้งก่อนตัดการเชื่อมต่อ)
DISCONNECTED = "disconnected"  # ใช้ภายใน client เท่านั้น (ไม่ได้ส่งผ่านเครือข่าย)
                               # เอาไว้บอก GUI ว่า "การเชื่อมต่อหลุดแล้ว"
def encode(msg: dict) -> bytes:
    """แปลง dict -> ข้อความ JSON -> bytes พร้อมต่อท้ายด้วย \\n เพื่อส่งผ่านเครือข่าย
    ensure_ascii=False ทำให้ภาษาไทยถูกเก็บเป็นตัวอักษรไทยจริงๆ
    ไม่ถูกแปลงเป็นรหัสแปลกๆ เช่น \\u0e2a
    """
    return (json.dumps(msg, ensure_ascii=False) + "\n").encode("utf-8")
def decode(line: str) -> dict:
    """แปลงข้อความ 1 บรรทัดที่รับมา กลับเป็น dict
    ถ้าบรรทัดว่าง หรือข้อมูลเสีย/ไม่ใช่ JSON จะคืน dict ว่าง {}
    (ผู้เรียกใช้ต้องเช็กเองว่าได้ค่าว่างหรือไม่ โปรแกรมจะได้ไม่พังเวลาเจอข้อมูลแปลกๆ)
    """
    line = line.strip()
    if not line:
        return {}
    try:
        return json.loads(line)
    except json.JSONDecodeError:
        return {}