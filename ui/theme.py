"""
ui/theme.py  -  ชุดสีน่ารักๆ และตัวสุ่มสีหน้าต่าง
======================================================================
เก็บ "สี" ทั้งหมดของโปรแกรมไว้ที่เดียว หน้าอื่นๆ (login_frame, chat_frame)
แค่รับชุดสีไปใช้ ไม่ต้องรู้ว่าสีจริงๆ คืออะไร
ข้อดี: อยากเพิ่มธีมใหม่ แค่เพิ่ม Palette(...) ต่อท้ายลิสต์ PALETTES ไม่ต้องแก้ที่อื่น
"""
import random
import zlib
from dataclasses import dataclass
@dataclass(frozen=True)   # dataclass = คลาสเก็บข้อมูลแบบสั้นๆ, frozen = ห้ามแก้ค่าหลังสร้าง
class Palette:
    """ชุดสี 1 ธีม (สีเป็นรหัสฐานสิบหก เช่น "#FF8FAB")"""
    name: str            # ชื่อธีม
    emoji: str           # อีโมจิประจำธีม
    bg: str              # พื้นหลังหน้าต่าง
    header: str          # แถบหัว / แผงสมาชิก / กล่องช่องพิมพ์
    primary: str         # สีปุ่มหลัก และสีขอบช่องกรอก
    primary_hover: str   # สีปุ่มตอนเอาเมาส์ไปชี้ (เข้มขึ้นนิดนึง)
    mine: str            # สีฟองข้อความของ "เรา"
    other: str           # สีฟองข้อความของ "คนอื่น"
    text: str            # สีตัวอักษรหลัก
    muted: str           # สีตัวอักษรจางๆ (เวลา, คำอธิบาย)
    on_primary: str = "#FFFFFF"   # สีตัวอักษรบนปุ่มหลัก (ค่าเริ่มต้นสีขาว)
# รายการธีมทั้งหมด ตอนเข้ากลุ่มโปรแกรมจะสุ่มหยิบมา 1 ธีม
PALETTES = [
    Palette("สตรอว์เบอร์รี", "🍓", "#FFF0F5", "#FFD9E4", "#F0668F", "#DC4F7A",
            "#FFC2D4", "#FFFFFF", "#5A3340", "#B07C8B"),
    Palette("มิ้นต์", "🌿", "#EEFBF4", "#CFF1DF", "#3FB586", "#2E9B72",
            "#B8EBD3", "#FFFFFF", "#24493B", "#6F9D8A"),
    Palette("ลาเวนเดอร์", "🔮", "#F5F0FF", "#E1D5FB", "#9B7BEA", "#8660D8",
            "#D4C4F9", "#FFFFFF", "#3F3360", "#8F82B3"),
    Palette("พีช", "🍑", "#FFF4EC", "#FFDCC4", "#F28C52", "#DE763C",
            "#FFD0AE", "#FFFFFF", "#5A3A28", "#B5896F"),
    Palette("ท้องฟ้า", "☁️", "#EEF7FF", "#CBE6FF", "#4DA3F0", "#358CDB",
            "#B7DBFF", "#FFFFFF", "#27425E", "#7E9BB8"),
    # ธีมเลมอนปุ่มสีเหลืองสว่าง ตัวอักษรขาวจะอ่านยาก เลยใช้สีน้ำตาลเข้มแทน
    Palette("เลมอน", "🍋", "#FFFCE8", "#FFF2A8", "#E6B800", "#CCA200",
            "#FFEC8A", "#FFFFFF", "#524712", "#A39A5C", on_primary="#4A3F00"),
]
# สีประจำตัวของสมาชิก (ใช้ทำวงกลมตัวอักษรแรกของชื่อ และสีชื่อบนฟองข้อความ)
# เลือกสีที่เข้มพอให้อ่านง่ายบนพื้นขาว
NAME_COLORS = ["#E0527A", "#E07B39", "#3AA17E", "#4A90D9",
               "#8E6BD1", "#C2478F", "#2F9E9E", "#C99A0B"]

def random_palette(exclude=None):
    """สุ่มธีมสี 1 ธีม โดยไม่ซ้ำกับธีมเดิมที่ส่งมาใน exclude
    (ถ้าสุ่มได้ธีมเดิมซ้ำ ผู้ใช้จะรู้สึกว่าสีไม่เปลี่ยน)
    """
    choices = [p for p in PALETTES if p != exclude] or PALETTES
    return random.choice(choices)
def color_for(name: str) -> str:
    """คืนสีประจำตัวของชื่อนี้
    ชื่อเดิมจะได้สีเดิมเสมอ ไม่ว่าจะเปิดกี่ครั้งหรือดูจากเครื่องไหน
    วิธีคือแปลงชื่อเป็นตัวเลข (crc32) แล้วหารเอาเศษด้วยจำนวนสีที่มี
    (ไม่ใช้ฟังก์ชัน hash() ของ Python เพราะมันให้ค่าไม่เหมือนเดิมทุกครั้งที่เปิดโปรแกรม)
    """
    return NAME_COLORS[zlib.crc32(name.encode("utf-8")) % len(NAME_COLORS)]
